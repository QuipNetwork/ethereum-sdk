// Generates the base64-inlined SHRINCS wasm module consumed by the browser
// loader. Inlining makes the SDK consumable by ANY frontend bundler with zero
// config: there is no `.wasm` asset to emit/resolve (the `new URL(...,
// import.meta.url)` asset pattern is unreliable across bundlers and library
// builds), so the browser loader instantiates straight from bytes.
//
// Re-run after re-vendoring the wasm (the `copy-wasm` build step invokes it).

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const wasmPath = join(root, "src/v1/shrincs/wasm/web/hashsigs_rs_bg.wasm");
const outPath = join(root, "src/v1/shrincs/wasm/web/inline.ts");

const base64 = readFileSync(wasmPath).toString("base64");

const banner = `// Copyright (C) 2025 quip.network
//
// SPDX-License-Identifier: AGPL-3.0-or-later
//
// GENERATED by scripts/gen-wasm-inline.mjs from hashsigs_rs_bg.wasm. Do not edit.
// Base64-inlined SHRINCS wasm so the browser loader needs no asset emission.
`;

writeFileSync(outPath, `${banner}\nexport const wasmBase64 = "${base64}";\n`);
console.log(`gen-wasm-inline: wrote ${outPath} (${base64.length} b64 chars)`);
